import assert from "node:assert/strict";
import {MarketDataClient} from "../examples/unified-dashboard.mjs";
const calls = [];
const client = new MarketDataClient("https://company.example", async url => {
  calls.push(new URL(url));
  return {ok: true, json: async () => ({items: []})};
});
const iran = {provider: "tsetmc", provider_symbol: "900000000000000001"};
await client.latest(iran);
assert.equal(calls.at(-1).pathname, "/api/v1/tsetmc/latest");
await client.history(iran, {start:"2026-01-01", end:"2027-01-01", interval:"1d"});
assert.equal(calls.at(-1).searchParams.get("selection"), "finalized");
assert.throws(() => client.history(iran, {interval:"1m"}), /native daily/);
await client.history({provider:"tradingview_guest", canonical_symbol:"CRYPTO:BTCUSDT"}, {start:"2026-01-01T00:00:00Z", end:"2026-01-02T00:00:00Z"});
assert.equal(calls.at(-1).pathname, "/api/v1/candles");
assert.equal(new URL(client.streamURL(iran, "cursor")).searchParams.get("after"), "cursor");
const international = {provider:"tradingview_guest", canonical_symbol:"FX:EURUSD", provider_symbol:"OANDA:EURUSD"};
await client.latest(international);
assert.equal(calls.at(-1).searchParams.get("provider_symbol"), "OANDA:EURUSD");
await client.history(international, {start:"2026-01-01T00:00:00Z", end:"2026-01-02T00:00:00Z"});
assert.equal(calls.at(-1).searchParams.get("provider_symbol"), "OANDA:EURUSD");
assert.deepEqual(client.streamSubscription(international), {action:"subscribe", symbols:["FX:EURUSD"]});
assert.equal(client.streamSubscription(iran), null);
assert.throws(() => client.streamURL(international, "cursor"), /replay uses changes/);
await client.changes(international, "last", {until:"barrier"});
assert.equal(calls.at(-1).pathname, "/api/v1/marketdata/changes");
assert.equal(calls.at(-1).searchParams.get("after"), "last");
assert.equal(calls.at(-1).searchParams.get("until"), "barrier");
await client.changes(iran, "last");
assert.equal(calls.at(-1).pathname, "/api/v1/tsetmc/changes");
assert.equal(calls.at(-1).searchParams.get("ins_code"), iran.provider_symbol);
console.log("Unified dashboard routing passed");
